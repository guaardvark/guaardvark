#!/bin/bash
# start_redis.sh - auto-provision and start a local Redis server for development
# Handles installation, authentication setup, and .env credential management.

# shellcheck source=scripts/lib/terminal_ui.sh
. "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/scripts/lib/terminal_ui.sh"

PORT=${REDIS_PORT:-6379}
SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
ENV_FILE="$SCRIPT_DIR/.env"
# The packaged config is a dpkg conffile and is never rewritten here: a modified
# conffile makes a later redis upgrade stop at dpkg's "modified configuration
# file" prompt. Guaardvark's settings live in their own file, which a systemd
# drop-in loads after the packaged one (`--include`, so the password is never a
# command-line argument).
REDIS_CONF="/etc/redis/redis.conf"
GV_REDIS_CONF="/etc/redis/guaardvark.conf"
GV_REDIS_DROPIN="/etc/systemd/system/redis-server.service.d/guaardvark.conf"
# First line of the whole-file redis.conf earlier versions of this script wrote.
GV_LEGACY_CONF_HEADER="# Guaardvark Redis config — auto-generated by start_redis.sh"
# Present once an install has been checked for that legacy file.
GV_LEGACY_CHECKED="$SCRIPT_DIR/data/.redis_conf_checked"
PIDS_DIR="$SCRIPT_DIR/pids"
REDIS_PID_FILE="$PIDS_DIR/redis.pid"
# Sidecar data dir (not /tmp alone) so we can find our process after restart.
REDIS_ALT_DIR="${REDIS_ALT_DIR:-$SCRIPT_DIR/data/redis-broker}"

command_exists() { command -v "$1" >/dev/null 2>&1; }

# ─── Helper: extract Redis password from .env ────────────────────────────────

get_redis_password() {
  if [ -f "$ENV_FILE" ] && grep -q "^REDIS_URL=" "$ENV_FILE"; then
    # Extract password from redis://:PASSWORD@host:port/db
    sed -n 's|^REDIS_URL=redis://:\([^@]*\)@.*|\1|p' "$ENV_FILE"
  fi
}

get_redis_url_port() {
  local url port
  if [ ! -f "$ENV_FILE" ]; then
    return
  fi
  url=$(grep "^REDIS_URL=" "$ENV_FILE" 2>/dev/null | tail -1 | sed 's/^REDIS_URL=//')
  [ -n "$url" ] || return
  port=$(echo "$url" | sed -E 's|^redis://([^@]*@)?[^:]+:([0-9]+).*|\2|')
  [ -n "$port" ] && echo "$port"
}

get_redis_url_raw() {
  if [ -f "$ENV_FILE" ]; then
    grep "^REDIS_URL=" "$ENV_FILE" 2>/dev/null | tail -1 | sed 's/^REDIS_URL=//'
  fi
}

# redis-cli with $AUTH_PASS, when set, passed through the environment rather
# than as -a, which would show it in the process list.
rcli() {
  if [ -n "${AUTH_PASS:-}" ]; then
    REDISCLI_AUTH="$AUTH_PASS" redis-cli "$@"
  else
    redis-cli "$@"
  fi
}

# ─── Helper: test Redis connectivity (with or without auth) ─────────────────

redis_ping() {
  local pass="$1"
  local port="${2:-$PORT}"
  if [ -n "$pass" ]; then
    # REDISCLI_AUTH, not -a: keeps the password out of the process list.
    REDISCLI_AUTH="$pass" redis-cli -p "$port" ping 2>/dev/null | grep -q PONG
  else
    redis-cli -p "$port" ping 2>/dev/null | grep -q PONG
  fi
}

redis_port_listening() {
  local port="${1:-$PORT}"
  if command_exists ss; then
    ss -tln 2>/dev/null | grep -q ":${port}\b"
    return $?
  fi
  if command_exists lsof; then
    lsof -ti "tcp:${port}" >/dev/null 2>&1
    return $?
  fi
  return 1
}

redis_auth_required() {
  local port="${1:-$PORT}"
  local out
  out=$(redis-cli -p "$port" ping 2>&1 || true)
  echo "$out" | grep -qi NOAUTH
}

write_redis_env_urls() {
  local url="$1"
  [ -f "$ENV_FILE" ] || touch "$ENV_FILE"
  chmod 600 "$ENV_FILE" 2>/dev/null || true
  local _tmp="${ENV_FILE}.tmp.$$"
  grep -vE '^(REDIS_URL|CELERY_BROKER_URL|CELERY_RESULT_BACKEND)=' "$ENV_FILE" > "$_tmp" 2>/dev/null || true
  {
    echo "REDIS_URL=${url}"
    echo "CELERY_BROKER_URL=${url}"
    echo "CELERY_RESULT_BACKEND=${url}"
  } >> "$_tmp"
  mv "$_tmp" "$ENV_FILE"
  chmod 600 "$ENV_FILE"
}

# Non-interactive root writability check. The test runs inside a root shell as
# the shell's builtin rather than as `sudo -n test ...`: on Ubuntu 26.04 (sudo-rs
# 0.2.13, uutils coreutils) the bare form returns 1 for /etc/redis even with a
# NOPASSWD rule, so the password step was skipped and a second broker started on
# the alternate port. The shell form returns 0 there and on classic sudo alike.
sudo_can_write_dir() {
  sudo -n sh -c 'test -w "$1"' _ "$1" 2>/dev/null
}

# Print a root/redis-only (0640) file, with sudo -n when it is not readable.
# Prints nothing when it is missing or cannot be read without a prompt.
read_redis_file() {
  if [ -r "$1" ]; then
    cat "$1" 2>/dev/null
  else
    sudo -n cat "$1" 2>/dev/null
  fi
}

conf_requirepass() {  # $1 = config file
  read_redis_file "$1" | grep -E '^[[:space:]]*requirepass[[:space:]]' | tail -1 \
    | awk '{ print $2 }' | tr -d "\"'"
}

# The password the system Redis boots with: Guaardvark's file when the drop-in
# loads it (it is read last), otherwise the packaged config's own requirepass.
redis_conf_password() {
  local pass=""
  [ -f "$GV_REDIS_DROPIN" ] && pass=$(conf_requirepass "$GV_REDIS_CONF")
  [ -n "$pass" ] || pass=$(conf_requirepass "$REDIS_CONF")
  echo "$pass"
}

# The packaged unit's ExecStart, read from the unit file the package ships.
vendor_redis_execstart() {
  local frag
  frag=$(systemctl show -p FragmentPath --value redis-server.service 2>/dev/null)
  [ -n "$frag" ] && [ -f "$frag" ] || return 1
  grep -m1 -E '^ExecStart=' "$frag" | cut -d= -f2-
}

expected_redis_dropin() {
  local exec_start
  exec_start=$(vendor_redis_execstart) || return 1
  [ -n "$exec_start" ] || return 1
  cat <<EOF
# Written by Guaardvark's start_redis.sh. Runs the packaged Redis with
# $GV_REDIS_CONF loaded after $REDIS_CONF, which stays as the package
# ships it. Remove this file and $GV_REDIS_CONF to undo.
[Service]
ExecStart=
ExecStart=$exec_start --include $GV_REDIS_CONF
EOF
}

# Write Guaardvark's Redis settings and the drop-in that loads them. Returns 0
# when something changed (the service then needs a restart), 1 when nothing
# changed or it could not be written (no systemd unit, or no sudo without a
# prompt).
write_guaardvark_redis_conf() {  # $1 = password
  local pass="$1" want_conf want_dropin changed=1
  system_redis_unit_present || return 1
  sudo_can_write_dir "$(dirname "$GV_REDIS_CONF")" || return 1
  want_dropin=$(expected_redis_dropin) || return 1
  want_conf="# Written by Guaardvark's start_redis.sh; loaded after $REDIS_CONF by
# $GV_REDIS_DROPIN. Settings here win over that file.
requirepass $pass
# A failed background save (full disk, unwritable dir) would otherwise make
# Redis refuse every write, and Celery with it.
stop-writes-on-bgsave-error no"
  if [ "$(read_redis_file "$GV_REDIS_CONF")" != "$want_conf" ]; then
    printf '%s\n' "$want_conf" | sudo -n tee "$GV_REDIS_CONF" >/dev/null || return 1
    sudo -n chown redis:redis "$GV_REDIS_CONF" 2>/dev/null
    sudo -n chmod 640 "$GV_REDIS_CONF"
    changed=0
  fi
  if [ "$(cat "$GV_REDIS_DROPIN" 2>/dev/null)" != "$want_dropin" ]; then
    sudo -n mkdir -p "$(dirname "$GV_REDIS_DROPIN")" || return 1
    printf '%s\n' "$want_dropin" | sudo -n tee "$GV_REDIS_DROPIN" >/dev/null || return 1
    sudo -n systemctl daemon-reload >/dev/null 2>&1
    changed=0
  fi
  return $changed
}

# Earlier versions replaced the whole packaged redis.conf with a seven-line file.
# When that file is still exactly what was written (only its password and port
# vary), its password moves to Guaardvark's own file and the packaged config is
# put back from the installed package version. A file someone has edited since
# is left alone.
migrate_legacy_redis_conf() {
  local content pass ver tmp pristine
  content=$(read_redis_file "$REDIS_CONF")
  [ -n "$content" ] || return 1   # unreadable without a prompt: try next start
  mkdir -p "$(dirname "$GV_LEGACY_CHECKED")"
  if [ "$(printf '%s\n' "$content" | head -1)" != "$GV_LEGACY_CONF_HEADER" ]; then
    touch "$GV_LEGACY_CHECKED"
    return 0
  fi
  pass=$(printf '%s\n' "$content" | awk '$1 == "requirepass" { print $2 }' | tail -1)
  if [ -z "$pass" ] || [ "$content" != "$GV_LEGACY_CONF_HEADER
bind 127.0.0.1 ::1
port $PORT
requirepass $pass
daemonize no
dir /var/lib/redis
stop-writes-on-bgsave-error no" ]; then
    vader_info "$REDIS_CONF was written by an earlier Guaardvark and edited since; leaving it as it is."
    touch "$GV_LEGACY_CHECKED"
    return 0
  fi
  write_guaardvark_redis_conf "$pass" || [ -f "$GV_REDIS_DROPIN" ] || return 1
  ver=$(dpkg-query -W -f='${Version}' redis-server 2>/dev/null)
  tmp=$(mktemp -d 2>/dev/null) || return 1
  pristine=""
  if [ -n "$ver" ] && (cd "$tmp" && apt-get download -q "redis-server=$ver" >/dev/null 2>&1); then
    dpkg-deb --fsys-tarfile "$tmp"/redis-server_*.deb 2>/dev/null | tar -xO ./etc/redis/redis.conf > "$tmp/redis.conf" 2>/dev/null \
      && [ -s "$tmp/redis.conf" ] && pristine="$tmp/redis.conf"
  fi
  if [ -n "$pristine" ] && sudo -n install -m 0640 -o redis -g redis "$pristine" "$REDIS_CONF"; then
    vader_success "Restored the packaged $REDIS_CONF; Guaardvark's Redis settings are now in $GV_REDIS_CONF."
  else
    vader_warn "Could not fetch the packaged $REDIS_CONF (redis-server $ver); keeping the current one. Redis keeps its password either way."
  fi
  rm -rf "$tmp"
  touch "$GV_LEGACY_CHECKED"
  REDIS_CONF_WRITTEN=1
  return 0
}

# True when Redis on the port refuses unauthenticated commands and accepts this
# password. A passwordless server also answers PONG to `redis-cli -a`, so the
# NOAUTH check is what tells the two apart.
redis_accepts_password() {  # $1 = password, $2 = port
  [ -n "$1" ] && redis_auth_required "${2:-$PORT}" && redis_ping "$1" "${2:-$PORT}"
}

system_redis_unit_present() {
  [ -d /run/systemd/system ] && command_exists systemctl \
    && systemctl cat redis-server.service >/dev/null 2>&1
}

write_redis_pid() {
  local port="$1"
  local rpid=""
  mkdir -p "$PIDS_DIR"
  rpid=$(redis-cli -p "$port" INFO server 2>/dev/null | tr -d '\r' | sed -n 's/^process_id://p')
  if [ -n "$rpid" ]; then
    echo "$rpid" > "$REDIS_PID_FILE"
  fi
}

clear_redis_pid_if_dead() {
  if [ -f "$REDIS_PID_FILE" ]; then
    local old
    old=$(cat "$REDIS_PID_FILE" 2>/dev/null || true)
    if [ -z "$old" ] || ! kill -0 "$old" 2>/dev/null; then
      rm -f "$REDIS_PID_FILE"
    fi
  fi
}

# Sync .env to a reachable broker. Prefer default PORT when passwordless (or with
# known password) so we do not leave REDIS_URL stuck on a dead alt port (6380).
# Returns 0 and writes .env on success.
sync_env_to_reachable_broker() {
  local pass="${1:-$(get_redis_password)}"
  local env_port
  env_port=$(get_redis_url_port)

  # 1) Default port, passwordless — preferred durable path (systemd redis).
  if redis_ping "" "$PORT"; then
    write_redis_env_urls "redis://localhost:${PORT}/0"
    # Not our sidecar — drop stale alt pid if it pointed at a dead process.
    clear_redis_pid_if_dead
    if [ -n "$env_port" ] && [ "$env_port" != "$PORT" ]; then
      vader_success "Redis broker URL reset to :${PORT} (was stale :${env_port} in .env)."
    else
      vader_success "Redis broker URL set to :${PORT}."
    fi
    return 0
  fi

  # 2) Default port with password from .env.
  if [ -n "$pass" ] && redis_ping "$pass" "$PORT"; then
    write_redis_env_urls "redis://:${pass}@localhost:${PORT}/0"
    clear_redis_pid_if_dead
    vader_success "Redis broker URL set to :${PORT} (authenticated)."
    return 0
  fi

  # 3) Env-recorded alt port still alive.
  if [ -n "$env_port" ] && [ "$env_port" != "$PORT" ]; then
    if redis_ping "" "$env_port" || { [ -n "$pass" ] && redis_ping "$pass" "$env_port"; }; then
      if [ -n "$pass" ] && redis_ping "$pass" "$env_port"; then
        write_redis_env_urls "redis://:${pass}@localhost:${env_port}/0"
      else
        write_redis_env_urls "redis://localhost:${env_port}/0"
      fi
      write_redis_pid "$env_port"
      vader_success "Redis already running on port ${env_port}."
      return 0
    fi
  fi

  return 1
}

# When :6379 is owned by a passworded system Redis we cannot reconfigure (no sudo),
# start a local passwordless broker on the next free port and point .env at it.
# Prefer restarting the port recorded in .env (usually 6380) so URLs stay stable.
start_redis_alt_port() {
  local preferred=""
  local alt_port
  preferred=$(get_redis_url_port)
  if [ -n "$preferred" ] && [ "$preferred" -ge 6380 ] 2>/dev/null && [ "$preferred" -le 6399 ] 2>/dev/null; then
    alt_port="$preferred"
  else
    alt_port="${REDIS_ALT_PORT:-6380}"
  fi

  # If preferred port is free, use it; if occupied but not pingable, try next ports.
  if redis_port_listening "$alt_port" && ! redis_ping "" "$alt_port"; then
    alt_port=$((alt_port + 1))
  fi
  while redis_port_listening "$alt_port" && ! redis_ping "" "$alt_port"; do
    alt_port=$((alt_port + 1))
    if [ "$alt_port" -gt 6399 ]; then
      vader_error "No free Redis port found between 6380-6399."
      return 1
    fi
  done

  if redis_ping "" "$alt_port"; then
    write_redis_env_urls "redis://localhost:${alt_port}/0"
    write_redis_pid "$alt_port"
    vader_success "Redis broker already up on port ${alt_port}."
    return 0
  fi

  mkdir -p "$REDIS_ALT_DIR" "$PIDS_DIR"
  vader_warn "Port $PORT is in use with auth we cannot match — starting passwordless broker on :${alt_port}."
  redis-server --daemonize yes --port "$alt_port" --bind 127.0.0.1 --dir "$REDIS_ALT_DIR" \
    --stop-writes-on-bgsave-error no --save "" >/dev/null 2>&1
  sleep 2
  if redis_ping "" "$alt_port"; then
    write_redis_env_urls "redis://localhost:${alt_port}/0"
    write_redis_pid "$alt_port"
    vader_success "Redis broker running on port ${alt_port} (passwordless, local-only, pidfile)."
    return 0
  fi
  vader_error "Failed to start passwordless Redis on port ${alt_port}."
  return 1
}

# ─── macOS (Homebrew) branch ─────────────────────────────────────────────────
# No apt / systemd / /etc/redis on macOS. Use Homebrew + brew services, which run
# Redis on 127.0.0.1:6379 passwordless — fine for local broker/cache use. This
# block fully handles macOS and exits; the Linux flow below never runs there.
if [ "$(uname -s)" = "Darwin" ]; then
  if ! redis_ping ""; then
    if ! command_exists redis-server; then
      if command_exists brew; then
        vader_info "Installing Redis via Homebrew..."
        brew install redis >/dev/null 2>&1 || { vader_error "brew install redis failed. Run: brew install redis"; exit 1; }
      else
        vader_error "Homebrew not found. Install from https://brew.sh, then: brew install redis"
        exit 1
      fi
    fi
    vader_info "Starting Redis via brew services..."
    brew services start redis >/dev/null 2>&1
    sleep 2
    if ! redis_ping ""; then
      # brew services can lag or be unavailable — fall back to a direct daemon.
      redis-server --daemonize yes --port "$PORT" --bind 127.0.0.1 --save "" >/dev/null 2>&1
      sleep 2
    fi
  fi

  if redis_ping ""; then
    vader_success "Redis running on port $PORT."
  else
    vader_error "Redis failed to start. Run: brew services start redis"
    exit 1
  fi

  # Point Celery/Redis at the local passwordless broker (idempotent rewrite).
  if [ -f "$ENV_FILE" ]; then
    NEW_URL="redis://localhost:${PORT}/0"
    if ! grep -q "^REDIS_URL=${NEW_URL}$" "$ENV_FILE"; then
      _tmp="${ENV_FILE}.tmp.$$"
      grep -vE '^(REDIS_URL|CELERY_BROKER_URL|CELERY_RESULT_BACKEND)=' "$ENV_FILE" > "$_tmp"
      {
        echo "REDIS_URL=${NEW_URL}"
        echo "CELERY_BROKER_URL=${NEW_URL}"
        echo "CELERY_RESULT_BACKEND=${NEW_URL}"
      } >> "$_tmp"
      mv "$_tmp" "$ENV_FILE"
      chmod 600 "$ENV_FILE"
      vader_success "Redis broker URL set to local passwordless (.env updated)."
    fi
  fi
  exit 0
fi

# ─── Step 1: Check if Redis is already running and reachable ─────────────────
# Critical: always leave REDIS_URL / CELERY_* pointing at a broker that PING's.
# A prior alt-port (6380) written to .env with a dead process used to pass
# "Redis already running" via :6379 while Celery still targeted :6380.

REDIS_PASS=$(get_redis_password)
ENV_REDIS_PORT=$(get_redis_url_port)
CONF_PASS=""
REDIS_CONF_WRITTEN=0
clear_redis_pid_if_dead

# Redis on :6379 wants a password that .env does not have. When that is the
# password in its config (an install whose .env lost it), write it back to .env
# rather than starting a second, passwordless broker on another port. The file
# is only read here and when provisioning, so healthy installs never call sudo.
if command_exists redis-cli && redis_auth_required "$PORT" \
   && ! { [ -n "$REDIS_PASS" ] && redis_ping "$REDIS_PASS" "$PORT"; }; then
  CONF_PASS=$(redis_conf_password)
  if redis_accepts_password "$CONF_PASS" "$PORT"; then
    write_redis_env_urls "redis://:${CONF_PASS}@localhost:${PORT}/0"
    REDIS_PASS="$CONF_PASS"
    ENV_REDIS_PORT="$PORT"
    vader_success "Redis credentials in .env now match the Redis config."
  fi
fi

# Installs from earlier versions keep Guaardvark's settings in the packaged
# config; move them out once (needs sudo without a prompt, so it is retried on
# later starts until it can run).
if [ -n "$REDIS_PASS" ] && [ ! -f "$GV_REDIS_DROPIN" ] && [ ! -f "$GV_LEGACY_CHECKED" ] \
   && system_redis_unit_present; then
  migrate_legacy_redis_conf || true
fi
# After a redis-server upgrade that changes the packaged ExecStart, rewrite the
# drop-in from it so the package's own start options still apply.
if [ -f "$GV_REDIS_DROPIN" ] && system_redis_unit_present \
   && [ "$(cat "$GV_REDIS_DROPIN" 2>/dev/null)" != "$(expected_redis_dropin)" ]; then
  _gv_pass=$(conf_requirepass "$GV_REDIS_CONF")
  if [ -n "$_gv_pass" ] && write_guaardvark_redis_conf "$_gv_pass"; then
    REDIS_CONF_WRITTEN=1
    vader_info "Updated $GV_REDIS_DROPIN for the installed redis-server."
  fi
fi
if [ "$REDIS_CONF_WRITTEN" = 1 ] && systemctl is-active --quiet redis-server 2>/dev/null; then
  sudo -n systemctl restart redis-server >/dev/null 2>&1 && sleep 1
  REDIS_CONF_WRITTEN=0
fi

if command_exists redis-cli; then
  # Stale .env port (e.g. 6380 down) but default PORT alive → rewrite .env now.
  if sync_env_to_reachable_broker "$REDIS_PASS"; then
    # Optional: fix dir/save on default PORT when we own the password path.
    if redis_ping "$REDIS_PASS" "$PORT" || redis_ping "" "$PORT"; then
      AUTH_PASS=""
      if [ -n "$REDIS_PASS" ] && redis_ping "$REDIS_PASS" "$PORT"; then
        AUTH_PASS="$REDIS_PASS"
      fi
      if [ -n "$AUTH_PASS" ] || redis_ping "" "$PORT"; then
        CURRENT_DIR=$(rcli -p "$PORT" CONFIG GET dir 2>/dev/null | tail -1)
        if [ "$CURRENT_DIR" = "/" ] || [ -z "$CURRENT_DIR" ]; then
          rcli -p "$PORT" CONFIG SET save "" >/dev/null 2>&1
          rcli -p "$PORT" CONFIG SET stop-writes-on-bgsave-error no >/dev/null 2>&1
        else
          rcli -p "$PORT" CONFIG SET stop-writes-on-bgsave-error no >/dev/null 2>&1
        fi
      fi
    fi
    exit 0
  fi

  # Env alt port dead — try restart sidecar on that port before broader install path.
  if [ -n "$ENV_REDIS_PORT" ] && [ "$ENV_REDIS_PORT" != "$PORT" ]; then
    vader_warn "Broker in .env (:$ENV_REDIS_PORT) is down — restarting local passwordless broker."
    start_redis_alt_port && exit 0
  fi

  # Port is listening but our ping failed — common when system Redis has a password
  # we no longer have in .env (e.g. after .env was trimmed) and we lack sudo to
  # rewrite /etc/redis/redis.conf.
  if redis_port_listening "$PORT"; then
    if redis_auth_required "$PORT" && [ -z "$REDIS_PASS" ]; then
      vader_warn "Redis on port $PORT requires authentication but .env has no password."
      vader_info "If that is the Redis this script configured, run 'sudo -v' and start again so its password can be read from the Redis config."
      start_redis_alt_port && exit 0
      exit 1
    fi
    if redis_ping ""; then
      write_redis_env_urls "redis://localhost:${PORT}/0"
      vader_success "Redis already running on port $PORT (passwordless)."
      exit 0
    fi
    if [ -n "$REDIS_PASS" ]; then
      vader_warn "Redis is listening on port $PORT but .env credentials were rejected."
      start_redis_alt_port && exit 0
      exit 1
    fi
  fi
fi

# ─── Step 2: Ensure redis-server is installed ────────────────────────────────

if ! command_exists redis-server; then
  vader_info "redis-server not found. Installing Redis..."
  if command_exists apt-get; then
    sudo apt-get update -qq >/dev/null 2>&1
    if sudo apt-get install -y redis-server >/dev/null 2>&1; then
      vader_success "Redis installed."
    else
      vader_error "Failed to install Redis. Install manually: sudo apt-get install -y redis-server"
      exit 1
    fi
  else
    vader_error "redis-server not found and apt-get not available. Install Redis manually."
    exit 1
  fi
fi


# ─── Step 3: Provision Redis authentication if not already configured ────────

# A password already in the config is the one the system Redis will run with.
if [ -z "$CONF_PASS" ]; then
  CONF_PASS=$(redis_conf_password)
fi
if [ -n "$CONF_PASS" ]; then
  REDIS_PASS="$CONF_PASS"
fi

if [ -z "$REDIS_PASS" ]; then
  vader_info "Provisioning Redis authentication..."
  REDIS_PASS=$(openssl rand -hex 20)

  if write_guaardvark_redis_conf "$REDIS_PASS"; then
    REDIS_CONF_WRITTEN=1
    vader_success "Redis password written to $GV_REDIS_CONF (loaded by $GV_REDIS_DROPIN)."
  elif system_redis_unit_present && [ ! -f "$GV_REDIS_DROPIN" ]; then
    # The system service cannot be configured without sudo: it would keep
    # running without a password, so do not claim one in .env.
    vader_warn "Cannot configure the redis-server service (no sudo). Redis will run without auth."
    if redis_port_listening "$PORT"; then
      vader_warn "Port $PORT already in use — will use an alternate local broker port."
      start_redis_alt_port && exit 0
      exit 1
    fi
    REDIS_PASS=""
  fi
  # No systemd service: the password is kept for the redis-server started below.

  # Update .env with Redis credentials (creating .env if needed: a password
  # only in the config locks Celery out at the next boot).
  if [ -n "$REDIS_PASS" ]; then
    write_redis_env_urls "redis://:${REDIS_PASS}@localhost:${PORT}/0"
    vader_success "Redis credentials written to .env"
  fi
elif [ -z "$CONF_PASS" ]; then
  # Password in .env but no config carries it — give it to the service.
  if write_guaardvark_redis_conf "$REDIS_PASS"; then
    REDIS_CONF_WRITTEN=1
    vader_success "Redis password from .env written to $GV_REDIS_CONF."
  fi
fi

# ─── Step 4: Start Redis service ─────────────────────────────────────────────

# A Redis already running (the package starts one on install) keeps the config
# it started with; after a config write it must restart, or it stays
# passwordless until the next boot while .env is rewritten to match it.
if [ "$REDIS_CONF_WRITTEN" = 1 ] && system_redis_unit_present \
   && systemctl is-active --quiet redis-server 2>/dev/null; then
  vader_info "Restarting redis service to load the new config..."
  sudo -n systemctl restart redis-server >/dev/null 2>&1 && sleep 1
fi

if command_exists systemctl; then
  vader_info "Attempting to start redis service via systemctl..."
  if systemctl --user start redis-server >/dev/null 2>&1 || sudo -n systemctl start redis-server >/dev/null 2>&1; then
    sleep 2
    if command_exists redis-cli && sync_env_to_reachable_broker "$REDIS_PASS"; then
      vader_success "Redis service started via systemctl."
      exit 0
    fi
  fi
fi

# ─── Step 5: Fallback - start redis-server directly ─────────────────────────

vader_info "Starting redis-server directly on port $PORT..."
if redis_port_listening "$PORT"; then
  vader_warn "Port $PORT is already in use."
  if redis_auth_required "$PORT" || [ -n "$REDIS_PASS" ]; then
    start_redis_alt_port && exit 0
  fi
  if redis_ping ""; then
    write_redis_env_urls "redis://localhost:${PORT}/0"
    vader_success "Redis already running on port $PORT."
    exit 0
  fi
  vader_error "Port $PORT is occupied and not reachable with current credentials."
  exit 1
fi
if [ -n "$REDIS_PASS" ]; then
  # The password goes in on stdin (`-` reads config from it), not as an argument.
  printf 'requirepass %s\n' "$REDIS_PASS" | redis-server - --daemonize yes --port "$PORT" --bind "127.0.0.1 ::1" --dir /tmp --stop-writes-on-bgsave-error no >/dev/null 2>&1
else
  redis-server --daemonize yes --port "$PORT" --dir /tmp --stop-writes-on-bgsave-error no >/dev/null 2>&1
fi
sleep 2
if command_exists redis-cli && redis_ping "$REDIS_PASS"; then
  if [ -n "$REDIS_PASS" ]; then
    write_redis_env_urls "redis://:${REDIS_PASS}@localhost:${PORT}/0"
  else
    write_redis_env_urls "redis://localhost:${PORT}/0"
  fi
  vader_success "redis-server started on port $PORT."
  exit 0
else
  # Last resort: sidecar when direct start on PORT failed.
  start_redis_alt_port && exit 0
  vader_error "Failed to start redis-server."
  exit 1
fi
